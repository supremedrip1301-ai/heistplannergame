PROMPT Creating procedure HP_SAVE_RUN ...

-- Save one run. Modelled on my Program 4 (PROCESS_ORDER: SELECT ... INTO,
-- IF check, INSERT, NO_DATA_FOUND handler) and Program 5 (named
-- exceptions for invalid input). It does NOT commit: Python commits.
CREATE OR REPLACE PROCEDURE hp_save_run (
    p_player_name IN  VARCHAR2,
    p_mission_id  IN  VARCHAR2,
    p_result      IN  VARCHAR2,
    p_score       IN  NUMBER,
    p_moves       IN  NUMBER,
    p_route_cost  IN  NUMBER,
    p_kit_summary IN  VARCHAR2,
    p_alert       IN  VARCHAR2,
    p_run_id      OUT NUMBER
)
IS
    v_player_id    hp_players.player_id%TYPE;
    v_mission_name hp_missions.mission_name%TYPE;
    v_name         hp_players.player_name%TYPE;

    invalid_numbers EXCEPTION;
    invalid_result  EXCEPTION;
    invalid_player  EXCEPTION;
BEGIN
    -- 1. Validate the numbers and flags.
    IF p_score IS NULL OR p_score < 0
       OR p_moves IS NULL OR p_moves < 0
       OR p_route_cost IS NULL OR p_route_cost < 0 THEN
        RAISE invalid_numbers;
    END IF;

    IF p_result IS NULL OR p_result NOT IN ('SUCCESS', 'ABANDONED')
       OR p_alert IS NULL OR p_alert NOT IN ('Y', 'N') THEN
        RAISE invalid_result;
    END IF;

    v_name := TRIM(p_player_name);
    IF v_name IS NULL THEN
        RAISE invalid_player;
    END IF;

    -- 2. The mission must exist (SELECT ... INTO with NO_DATA_FOUND).
    BEGIN
        SELECT mission_name INTO v_mission_name
          FROM hp_missions
         WHERE mission_id = p_mission_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20002, 'Unknown mission: ' || p_mission_id);
    END;

    -- 3. Find the player, or create them if this is their first run.
    BEGIN
        SELECT player_id INTO v_player_id
          FROM hp_players
         WHERE player_name = v_name;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            BEGIN
                INSERT INTO hp_players (player_name)
                VALUES (v_name)
                RETURNING player_id INTO v_player_id;
            EXCEPTION
                -- Safe against the UNIQUE constraint: another session may
                -- have created the same name a moment ago.
                WHEN DUP_VAL_ON_INDEX THEN
                    SELECT player_id INTO v_player_id
                      FROM hp_players
                     WHERE player_name = v_name;
            END;
    END;

    -- 4. Store the run and hand its new ID back through the OUT parameter.
    INSERT INTO hp_mission_runs (player_id, mission_id, result, score, moves,
                                 route_cost, kit_summary, alert_triggered)
    VALUES (v_player_id, p_mission_id, p_result, p_score, p_moves,
            p_route_cost, p_kit_summary, p_alert)
    RETURNING run_id INTO p_run_id;

    -- No COMMIT here on purpose: the caller (Python) owns the transaction.
EXCEPTION
    WHEN invalid_numbers THEN
        RAISE_APPLICATION_ERROR(-20001, 'Score, moves and route cost must be zero or more.');
    WHEN invalid_result THEN
        RAISE_APPLICATION_ERROR(-20003, 'Result must be SUCCESS or ABANDONED, alert Y or N.');
    WHEN invalid_player THEN
        RAISE_APPLICATION_ERROR(-20004, 'Player name must not be empty.');
END;
/

PROMPT Creating procedure HP_GET_STATS ...

-- Statistics for one player (or all players when p_player_name is NULL).
-- An aggregate query without GROUP BY always returns exactly one row, and
-- NVL turns "no data" into zeros, so an unknown player gives 0, never NULL.
CREATE OR REPLACE PROCEDURE hp_get_stats (
    p_player_name  IN  VARCHAR2,
    p_total_runs   OUT NUMBER,
    p_success_runs OUT NUMBER,
    p_best_score   OUT NUMBER,
    p_avg_score    OUT NUMBER
)
IS
BEGIN
    SELECT COUNT(r.run_id),
           NVL(SUM(CASE WHEN r.result = 'SUCCESS' THEN 1 ELSE 0 END), 0),
           NVL(MAX(r.score), 0),
           NVL(ROUND(AVG(CASE WHEN r.result = 'SUCCESS' THEN r.score END), 2), 0)
      INTO p_total_runs, p_success_runs, p_best_score, p_avg_score
      FROM hp_mission_runs r
      JOIN hp_players p ON p.player_id = r.player_id
     WHERE p_player_name IS NULL
        OR p.player_name = p_player_name;
END;
/

PROMPT Creating procedure HP_PRINT_RECENT_RUNS ...

-- Report for an SQL worksheet / SQL*Plus demo (not called by the game).
-- My Program 2 explicit-cursor pattern: OPEN, FETCH, EXIT WHEN %NOTFOUND, CLOSE.
CREATE OR REPLACE PROCEDURE hp_print_recent_runs (p_limit IN NUMBER)
IS
    CURSOR recent_cursor IS
        SELECT r.run_id, p.player_name, m.mission_name, r.result, r.score,
               hp_rank_title(r.score) AS rank_title, r.played_at
          FROM hp_mission_runs r
          JOIN hp_players p  ON p.player_id = r.player_id
          JOIN hp_missions m ON m.mission_id = r.mission_id
         ORDER BY r.run_id DESC;

    v_run_id   hp_mission_runs.run_id%TYPE;
    v_player   hp_players.player_name%TYPE;
    v_mission  hp_missions.mission_name%TYPE;
    v_result   hp_mission_runs.result%TYPE;
    v_score    hp_mission_runs.score%TYPE;
    v_rank     VARCHAR2(20);
    v_played   hp_mission_runs.played_at%TYPE;
    v_count    NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('RECENT MISSION RUNS');
    DBMS_OUTPUT.PUT_LINE('-------------------');

    OPEN recent_cursor;
    LOOP
        FETCH recent_cursor INTO v_run_id, v_player, v_mission, v_result,
                                 v_score, v_rank, v_played;
        EXIT WHEN recent_cursor%NOTFOUND OR v_count >= NVL(p_limit, 5);

        v_count := v_count + 1;
        DBMS_OUTPUT.PUT_LINE('Run ' || v_run_id || ' | ' || v_player || ' | '
                             || v_mission || ' | ' || v_result || ' | score '
                             || v_score || ' (' || v_rank || ') | '
                             || TO_CHAR(v_played, 'YYYY-MM-DD HH24:MI'));
    END LOOP;
    CLOSE recent_cursor;

    IF v_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE('No missions on record yet.');
    END IF;
END;
/

