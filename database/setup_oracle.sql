PROMPT Creating tables ...

-- Players: one row per operative name.
CREATE TABLE hp_players (
    player_id   NUMBER GENERATED BY DEFAULT AS IDENTITY
                CONSTRAINT hp_players_pk PRIMARY KEY,
    player_name VARCHAR2(30) NOT NULL
                CONSTRAINT hp_players_name_uk UNIQUE,
    created_at  DATE DEFAULT SYSDATE NOT NULL
);

-- Missions: the three fixed missions of the game.
CREATE TABLE hp_missions (
    mission_id   VARCHAR2(20) CONSTRAINT hp_missions_pk PRIMARY KEY,
    mission_name VARCHAR2(50) NOT NULL,
    difficulty   VARCHAR2(10) NOT NULL
);

-- Mission runs: one row per finished or abandoned run.
CREATE TABLE hp_mission_runs (
    run_id          NUMBER GENERATED BY DEFAULT AS IDENTITY
                    CONSTRAINT hp_runs_pk PRIMARY KEY,
    player_id       NUMBER NOT NULL
                    CONSTRAINT hp_runs_player_fk REFERENCES hp_players (player_id),
    mission_id      VARCHAR2(20) NOT NULL
                    CONSTRAINT hp_runs_mission_fk REFERENCES hp_missions (mission_id),
    result          VARCHAR2(12) NOT NULL
                    CONSTRAINT hp_runs_result_ck CHECK (result IN ('SUCCESS', 'ABANDONED')),
    score           NUMBER(6) NOT NULL
                    CONSTRAINT hp_runs_score_ck CHECK (score >= 0),
    moves           NUMBER(5) NOT NULL,
    route_cost      NUMBER(6) NOT NULL,
    kit_summary     VARCHAR2(200),
    alert_triggered CHAR(1) DEFAULT 'N' NOT NULL
                    CONSTRAINT hp_runs_alert_ck CHECK (alert_triggered IN ('Y', 'N')),
    played_at       DATE DEFAULT SYSDATE NOT NULL
);

-- Audit table + sequence (my college Program 6 pattern).
CREATE TABLE hp_run_audit (
    audit_id   NUMBER CONSTRAINT hp_run_audit_pk PRIMARY KEY,
    run_id     NUMBER NOT NULL,
    player_id  NUMBER NOT NULL,
    score      NUMBER(6),
    db_user    VARCHAR2(128),
    audited_at DATE
);

CREATE SEQUENCE hp_audit_seq START WITH 1 INCREMENT BY 1 NOCACHE;

