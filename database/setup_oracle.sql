-- Run as the application user HEIST (never as SYS/SYSTEM):
--   Windows installer (Route A), from the project folder:
--     sqlplus heist@localhost:1521/FREEPDB1 @database\setup_oracle.sql
--   WSL 2 container (Route B):
--     podman exec -it oracle26ai sqlplus heist@FREEPDB1 @/tmp/setup_oracle.sql
--
-- Target: Oracle AI Database 26ai Free (23.26.x, PDB FREEPDB1). The script
-- uses only syntax that also works on Oracle Database 19c: no
-- CREATE ... IF NOT EXISTS, no BOOLEAN columns, no multi-row VALUES, and
-- every SELECT without a table uses FROM dual. Identity columns need 12c+.
--
-- The script is RE-RUNNABLE: old objects are dropped first (missing
-- objects are ignored), and the missions are seeded with MERGE.
--
-- Three deliberate differences from my college PL/SQL programs:
--  1. The procedures do NOT COMMIT. The Python program owns the
--     transaction: it commits after a successful call, or rolls back.
--  2. Errors are NOT hidden with WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE.
--     Bad input is reported with RAISE_APPLICATION_ERROR(-200xx, ...),
--     which python-oracledb receives as a real exception.
--  3. Every comment starts with "--" (plain-sentence lines such as
--     "Validate minimum balance" would not compile).
-- =====================================================================
