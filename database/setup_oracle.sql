-- Score -> rank label, using CASE like my Program 3 alternative version.
-- The SQLite mode uses the same thresholds from core/scoring.py.
CREATE OR REPLACE FUNCTION hp_rank_title (p_score NUMBER)
RETURN VARCHAR2
IS
    v_title VARCHAR2(20);
BEGIN
    v_title := CASE
                   WHEN p_score >= 800 THEN 'Phantom'
                   WHEN p_score >= 650 THEN 'Specialist'
                   WHEN p_score >= 450 THEN 'Operative'
                   ELSE 'Rookie'
               END;
    RETURN v_title;
END;
