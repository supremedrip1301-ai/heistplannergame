PROMPT Creating trigger HP_TRG_RUN_AUDIT ...

-- My Program 6 audit trigger, adapted from AFTER UPDATE to AFTER INSERT:
-- every new run is copied into the audit table with the DB user and time.
CREATE OR REPLACE TRIGGER hp_trg_run_audit
AFTER INSERT ON hp_mission_runs
FOR EACH ROW
BEGIN
    INSERT INTO hp_run_audit (audit_id, run_id, player_id, score, db_user, audited_at)
    VALUES (hp_audit_seq.NEXTVAL, :NEW.run_id, :NEW.player_id, :NEW.score, USER, SYSDATE);
END;
